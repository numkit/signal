// signal/tests/arity_bounds_test.cpp
//
// Table-driven max-arity guards for the signal domain, generated from the
// R2025b-probed bounds applied in this migration (see
// bugs/opened/lang/reg-max-arity.md): calling with max+1 inputs must be
// REJECTED — the reference errors "Too many input arguments", nk must
// never silently drop extras. The checkNargin call is the first statement
// of every migrated reg, so dummy 1-arguments never reach the kernels.
// NOTE: parameterized suites are instantiated as SignalBounds/… — filter
// with *SignalArityBounds*.

#include <gtest/gtest.h>

#include <numkit/core/standard_engine.hpp>

#include <string>
#include <utility>
#include <vector>

class SignalArityBoundsTest : public ::testing::TestWithParam<std::pair<const char *, int>>
{
public:
    numkit::StandardEngine engine;
};

TEST_P(SignalArityBoundsTest, ExtraInputsRejected)
{
    const auto [fn, maxArgs] = GetParam();
    std::string call = fn;
    call += "(";
    for (int i = 0; i <= maxArgs; ++i) {
        if (i) call += ", ";
        call += "1";
    }
    call += ");";
    EXPECT_ANY_THROW(engine.eval(call)) << call;
}

